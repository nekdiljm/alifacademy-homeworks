package main

import "fmt"

/*
Даны три переменные вещественного типа: A, B, C. Если их значения
упорядочены по возрастанию, то удвоить их; в противном случае заменить значение каждой переменной на противоположное. Вывести новые
значения переменных A, B, C.
*/
func main() {
	var (
		a = 10.0
		b = 15.0
		c = 20.0
	)

	if a < b && a < c && b < c {
		a *= 2
		b *= 2
		c *= 2
	} else {
		a, b, c = -a, -b, -c
	}
	fmt.Println(a, b, c)
}
