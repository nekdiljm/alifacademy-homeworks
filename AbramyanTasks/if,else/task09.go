package main

import "fmt"

// Даны две переменные вещественного типа: A, B. Перераспределить значения данных переменных так, чтобы в A оказалось меньшее из значений,
// а в B — большее. Вывести новые значения переменных A и B.
func main() {
	var (
		a = 20.2
		b = 14.4
	)

	if a > b {
		a, b = b, a
		fmt.Printf("a = %.1f, b = %.1f", a, b)
	}
}
