package main

import "fmt"

//На основе массива из задачи 1 сделай срез, взяв несколько элементов из середины (например, со 2-го по 4-й). Выведи получившийся срез, а также его len и cap.

func main() {
	arr := [5]int{1, 2, 3, 4, 5}
	ar := arr[2:4]
	fmt.Printf("Значения среза - %v\nДлина - %v\nОбъем - %v", ar, len(ar), cap(ar))
}
